const normalize=s=>s.trim().replace(/\s/g,'').replace(/(?:特别行政区|壮族自治区|回族自治区|维吾尔自治区|自治区|省|市)$/,'');
export function searchRegions(query){const q=normalize(query);return !q?REGIONS:REGIONS.filter(r=>[r.name,...r.aliases].some(a=>normalize(a).includes(q)||q===normalize(a)));}
export function chooseRegion(previous,random=Math.random){const pool=REGIONS.filter(r=>r.id!==previous);return pool[Math.min(pool.length-1,Math.floor(random()*pool.length))];}
export class ScratchGrid {
 constructor(cols=96,rows=54){this.cols=cols;this.rows=rows;this.cells=new Uint8Array(cols*rows);this.count=0;}
 dab(x,y,r=4){let fresh=[];for(let j=Math.max(0,Math.floor(y-r));j<=Math.min(this.rows-1,Math.ceil(y+r));j++)for(let i=Math.max(0,Math.floor(x-r));i<=Math.min(this.cols-1,Math.ceil(x+r));i++){const k=j*this.cols+i;if((i-x)**2+(j-y)**2<=r*r&&!this.cells[k]){this.cells[k]=1;this.count++;fresh.push([i,j]);}}return fresh;}
 stroke(a,b,r=4){let fresh=[];const steps=Math.max(1,Math.ceil(Math.hypot(b.x-a.x,b.y-a.y)));for(let i=0;i<=steps;i++)fresh.push(...this.dab(a.x+(b.x-a.x)*i/steps,a.y+(b.y-a.y)*i/steps,r));return fresh;}
 get progress(){return this.count/this.cells.length;}
}
